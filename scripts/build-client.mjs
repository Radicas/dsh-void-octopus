import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))

const result = await build({
  entryPoints: [resolve(root, 'src/client-entry.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime'],
  loader: { '.js': 'jsx' },
  // Inlined so the running page can answer "which build am I actually looking
  // at?" with `__dshVoidOctopus.version` — a re-loaded plugin bundle is the
  // first thing to rule out when a visual bug is reported.
  define: { __PLUGIN_VERSION__: JSON.stringify(pkg.version) },
})

const body = result.outputFiles[0].text
const banner = `/* dsh-void-octopus — generated by scripts/build-client.mjs; do not edit by hand. */\n`
const wrapped =
  banner +
  `window.__ModuleLoader__.load({\n` +
  `  id: 'dsh-void-octopus',\n` +
  `  factory(require) {\n` +
  `    const module = { exports: {} };\n` +
  `    const exports = module.exports;\n` +
  body +
  `\n    return module.exports.default ?? module.exports;\n` +
  `  },\n` +
  `});\n`

const out = resolve(root, 'client.js')
writeFileSync(out, wrapped)
console.log(`client.js written: ${(wrapped.length / 1024).toFixed(1)} KiB`)
